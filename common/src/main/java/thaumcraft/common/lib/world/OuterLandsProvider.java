/**
 * The native provider of the TC4 Outer Lands dimension.
 *
 * The 1.7 {@code WorldProviderOuter} (oracle {@code thaumcraft/common/lib/world/dim/
 * WorldProviderOuter.java:30-133}) and its void chunk provider (oracle {@code ChunkProviderOuter.
 * java:38-127}) are replaced by the native 1.21 datapack route:
 * <ul>
 *   <li>{@code data/thaumcraft/dimension_type/outer_lands.json} carries the dimension type: no sky
 *       light, a fixed time of 0 (the original celestial angle is always 0), an ambient light of 0
 *       and the 256 block tall 1.7 world height.</li>
 *   <li>{@code data/thaumcraft/dimension/outer_lands.json} carries the level stem: a flat void
 *       generator with a single air layer and the Eldritch biome as its fixed biome source, which
 *       reproduces the empty chunks of the original chunk provider.</li>
 *   <li>{@code data/thaumcraft/worldgen/biome/eldritch.json} carries the biome.</li>
 * </ul>
 *
 * The labyrinth itself is generated by {@link OuterLandsMazeFeature}, which reads the cell map
 * the eldritch ring seeds and asks {@link DungeonRooms} for the room layout.
 */
public final class OuterLandsProvider {
    private OuterLandsProvider() {}

    /** The native dimension key of the Outer Lands. */
    public static final ResourceKey<Level> DIMENSION = ResourceKey.create(Registries.DIMENSION,
            ResourceLocation.fromNamespaceAndPath("thaumcraft", "outer_lands"));
    /** The native dimension type key of the Outer Lands. */
    public static final ResourceKey<DimensionType> DIMENSION_TYPE = ResourceKey.create(Registries.DIMENSION_TYPE,
            ResourceLocation.fromNamespaceAndPath("thaumcraft", "outer_lands"));

    /** The generator settings of the dimension: a single air layer over the fixed Eldritch biome. */
    public static final int VOID_LAYER_HEIGHT = 1;

    /** True when the given level is the Outer Lands. */
    public static boolean isOuterLands(Level level) {
        return level.dimension().equals(DIMENSION);
    }

    /**
     * The labyrinth cell store.
     *
     * Oracle {@code thaumcraft/common/lib/world/dim/MazeHandler.java:35-140} keeps the cells in a
     * static map and writes them to {@code labyrinth.dat} in the world folder. The native port
     * keeps the same map in the overworld saved data so that both dimensions share it and it
     * survives a restart.
     */
    public static final class MazeSavedData extends SavedData {
        public static final String ID = "thaumcraft_maze";
        private static final SavedData.Factory<MazeSavedData> FACTORY = new SavedData.Factory<>(
                MazeSavedData::new, MazeSavedData::load, DataFixTypes.LEVEL);
        private final Map<Long, Short> cells = new java.util.concurrent.ConcurrentHashMap<>();

        public MazeSavedData() {
        }

        public static MazeSavedData load(CompoundTag tag, HolderLookup.Provider registries) {
            MazeSavedData data = new MazeSavedData();
            ListTag list = tag.getList("cells", Tag.TAG_COMPOUND);
            for (int i = 0; i < list.size(); ++i) {
                CompoundTag entry = list.getCompound(i);
                data.cells.put(StructurePlacementRules.key(entry.getInt("x"), entry.getInt("z")),
                        entry.getShort("cell"));
            }
            return data;
        }

        @Override public CompoundTag save(CompoundTag tag, HolderLookup.Provider registries) {
            ListTag list = new ListTag();
            for (Map.Entry<Long, Short> entry : cells.entrySet()) {
                CompoundTag cell = new CompoundTag();
                cell.putInt("x", (int) (entry.getKey() >> 32));
                cell.putInt("z", (int) (entry.getKey() & 0xFFFFFFFFL));
                cell.putShort("cell", entry.getValue());
                list.add(cell);
            }
            tag.put("cells", list);
            return tag;
        }

        /** The packed cell of a chunk, 0 when the chunk carries no labyrinth. */
        public short cell(int chunkX, int chunkZ) {
            Short value = cells.get(StructurePlacementRules.key(chunkX, chunkZ));
            return value == null ? 0 : value;
        }

        /** True when a labyrinth already covers the given area. */
        public boolean mazesInRange(int chunkX, int chunkZ, int width, int height) {
            return StructurePlacementRules.mazesInRange(cells, chunkX, chunkZ, width, height);
        }

        /**
         * Stores a generated labyrinth. Oracle {@code MazeThread:29-68} writes the cells of the
         * grid into the map and removes the five empty corner markers.
         */
        public void storeLabyrinth(MazeGenerator generator, int ringChunkX, int ringChunkZ) {
            int column = StructurePlacementRules.mazeOriginChunk(ringChunkX, generator.width());
            int row = StructurePlacementRules.mazeOriginChunk(ringChunkZ, generator.height());
            for (int a = 0; a < generator.width(); ++a) {
                for (int b = 0; b < generator.height(); ++b) {
                    if (generator.grid[b][a] <= 0) continue;
                    cells.put(StructurePlacementRules.key(a + column, b + row), (short) generator.grid[b][a]);
                }
            }
            setDirty();
        }
    }

    /** The saved data of the world, created on demand. */
    public static MazeSavedData maze(ServerLevel level) {
        return level.getServer().overworld().getDataStorage().computeIfAbsent(MazeSavedData.FACTORY, MazeSavedData.ID);
    }

    /**
     * The feature that builds the Outer Lands rooms.
     *
     * Oracle {@code thaumcraft/common/lib/world/dim/MazeHandler.java:152-186} dispatches on the
     * labyrinth cell feature and calls the room generators. The native feature does the same for
     * the chunk it is placed in; the room connections that reach into the neighbouring chunk are
     * drawn by that neighbour, so no chunk ever writes outside of itself.
     */
    public static final class OuterLandsMazeFeature extends Feature<NoneFeatureConfiguration> {
        public OuterLandsMazeFeature() {
            super(NoneFeatureConfiguration.CODEC);
        }

        @Override public boolean place(FeaturePlaceContext<NoneFeatureConfiguration> context) {
            WorldGenLevel level = context.level();
            int chunkX = context.origin().getX() >> 4;
            int chunkZ = context.origin().getZ() >> 4;
            if (!(level.getLevel() instanceof ServerLevel server)) return false;
            MazeSavedData maze = maze(server);
            short packed = maze.cell(chunkX, chunkZ);
            if (packed == 0) return false;
            MazeGenerator.Cell cell = new MazeGenerator.Cell(packed);
            RandomSource random = context.random();
            // The original drew the decoration chances from the world random. The native port uses
            // a deterministic per chunk stream so the parallel chunk workers never share a stream.
            RandomSource worldRandom = level.getLevel().getChunkSource().randomState()
                    .getOrCreateRandomFactory(ResourceLocation.fromNamespaceAndPath("thaumcraft", "outer_lands"))
                    .at(chunkX, OuterLandsRules.MAZE_FLOOR_Y, chunkZ);
            DungeonRooms.Builder builder = new DungeonRooms.Builder();
            View view = new View(level, chunkX, chunkZ);
            int y = OuterLandsRules.MAZE_FLOOR_Y;
            int cx = chunkX;
            int cz = chunkZ;
            switch (OuterLandsRules.roomForFeature(cell.feature)) {
                case PORTAL -> DungeonRooms.generatePortal(builder, view, random, worldRandom, cx, cz, y, cell);
                case BOSS -> DungeonRooms.generateBossRoom(builder, view, random, worldRandom, cx, cz, y, cell);
                case KEY_ROOM -> DungeonRooms.generateKeyRoom(builder, view, random, worldRandom, cx, cz, y, cell,
                        level.getLevel().getDifficulty().getId());
                case NEST_ROOM -> DungeonRooms.generateNestRoom(builder, view, random, worldRandom, cx, cz, y, cell);
                case LIBRARY_ROOM -> DungeonRooms.generateLibraryRoom(builder, view, random, worldRandom, cx, cz, y, cell);
                case PASSAGE -> DungeonRooms.generatePassage(builder, view, random, worldRandom, cx, cz, y, cell);
            }
            apply(level, builder, random, worldRandom);
            return true;
        }

        private static void apply(WorldGenLevel level, DungeonRooms.Builder builder, RandomSource random,
                                  RandomSource worldRandom) {
            for (DungeonRooms.Placement placement : builder.placements) {
                BlockState state = ThaumcraftOuterLands.state(placement.kind(), placement.variant(), placement.facing());
                if (state == null) continue;
                int flags = switch (placement.kind()) {
                    case ELDRITCH_NOTHING, BEDROCK, AIR -> 0;
                    default -> Block.UPDATE_NEIGHBORS | Block.UPDATE_CLIENTS;
                };
                BlockPos pos = new BlockPos(placement.x(), placement.y(), placement.z());
                level.setBlock(pos, state, flags);
                if (placement.kind() != DungeonRooms.Kind.CRYSTAL) continue;
                // Oracle GenCommon:296-299 - the crystal points into the free neighbour.
                ThaumcraftOuterLands.configureCrystal(level.getBlockEntity(pos), placement.facing());
            }
            decorations(level, builder, random);
            ThaumcraftOuterLands.spawnRoomEntities(level, builder);
        }

        /** Oracle {@code GenCommon.processDecorations:279-317}. */
        private static void decorations(WorldGenLevel level, DungeonRooms.Builder builder, RandomSource random) {
            for (int[] pos : builder.urns) {
                if (!level.getBlockState(new BlockPos(pos[0], pos[1] + 1, pos[2])).isAir()) continue;
                BlockState base = ThaumcraftOuterLands.state(DungeonRooms.Kind.COSMETIC_SOLID, 15, -1);
                BlockState urn = ThaumcraftOuterLands.state(DungeonRooms.Kind.LOOT_URN,
                        OuterLandsRules.lootUrnMeta(random.nextFloat()), -1);
                if (base != null) level.setBlock(new BlockPos(pos[0], pos[1], pos[2]), base, Block.UPDATE_NEIGHBORS | Block.UPDATE_CLIENTS);
                if (urn != null) level.setBlock(new BlockPos(pos[0], pos[1] + 1, pos[2]), urn, Block.UPDATE_NEIGHBORS | Block.UPDATE_CLIENTS);
            }
            for (int[] pos : builder.commons) {
                BlockPos target = new BlockPos(pos[0], pos[1], pos[2]);
                int exposed = countExposedSides(level, target);
                if (exposed <= 0) continue;
                if (exposed != 1 && bedrockShowing(level, target)) continue;
                if (adjacentToEldritch(level, target)) continue;
                int meta = OuterLandsRules.commonDecorationMeta(random.nextInt(3), random.nextInt(8));
                BlockState state = ThaumcraftOuterLands.state(DungeonRooms.Kind.ELDRITCH, meta, -1);
                if (state == null) continue;
                level.setBlock(target, state, Block.UPDATE_NEIGHBORS | Block.UPDATE_CLIENTS);
                if (meta != 4 || random.nextInt(OuterLandsRules.CRYSTAL_DECORATION_CHANCE) != 0) continue;
                for (Direction direction : Direction.values()) {
                    BlockPos neighbour = target.relative(direction);
                    if (!level.getBlockState(neighbour).isAir()) continue;
                    BlockState crystal = ThaumcraftOuterLands.state(DungeonRooms.Kind.CRYSTAL, 7, direction.ordinal());
                    if (crystal == null) break;
                    level.setBlock(neighbour, crystal, Block.UPDATE_NEIGHBORS | Block.UPDATE_CLIENTS);
                    // Oracle GenCommon:297-298 - the crystal points into the free neighbour.
                    ThaumcraftOuterLands.configureCrystal(level.getBlockEntity(neighbour), direction.ordinal());
                    break;
                }
            }
            for (int[] pos : builder.crabSpawners) {
                BlockPos target = new BlockPos(pos[0], pos[1], pos[2]);
                if (countExposedSides(level, target) != 1) continue;
                if (adjacentToEldritch(level, target)) continue;
                BlockState state = ThaumcraftOuterLands.state(DungeonRooms.Kind.ELDRITCH, 9, -1);
                if (state == null) continue;
                level.setBlock(target, state, Block.UPDATE_NEIGHBORS | Block.UPDATE_CLIENTS);
                // Oracle GenCommon:307-312 - the crab spawner points into its free neighbour.
                for (Direction direction : Direction.values()) {
                    BlockPos neighbour = target.relative(direction);
                    if (!level.getBlockState(neighbour).isAir()) continue;
                    ThaumcraftOuterLands.configureFacing(level.getBlockEntity(target), (byte) direction.get3DDataValue());
                    break;
                }
            }
        }

        /** Oracle {@code BlockUtils.countExposedSides:282-289} - the number of air neighbours. */
        private static int countExposedSides(WorldGenLevel level, BlockPos pos) {
            int count = 0;
            for (Direction direction : Direction.values()) {
                if (!level.getBlockState(pos.relative(direction)).isAir()) continue;
                ++count;
            }
            return count;
        }

        /** Oracle {@code GenCommon.isBedrockShowing:319-325}. */
        private static boolean bedrockShowing(WorldGenLevel level, BlockPos pos) {
            for (Direction direction : Direction.values()) {
                if (level.getBlockState(pos.relative(direction)).isAir()) return true;
                BlockState opposite = level.getBlockState(pos.relative(direction.getOpposite()));
                if (opposite.is(ThaumcraftOuterLands.eldritchNothing()) || opposite.is(Blocks.BEDROCK)) return true;
            }
            return false;
        }

        /** Oracle {@code BlockUtils.isBlockAdjacentToAtleast:256-275} for the eldritch block. */
        private static boolean adjacentToEldritch(WorldGenLevel level, BlockPos pos) {
            for (int dx = -1; dx <= 1; ++dx) {
                for (int dy = -1; dy <= 1; ++dy) {
                    for (int dz = -1; dz <= 1; ++dz) {
                        if (dx == 0 && dy == 0 && dz == 0) continue;
                        if (ThaumcraftOuterLands.isEldritch(level.getBlockState(pos.offset(dx, dy, dz)))) return true;
                    }
                }
            }
            return false;
        }
    }

    /**
     * The world view of the room generators. Every query of the original room code stays inside
     * the chunk that is generated, so the view never leaves the generation region.
     */
    public static final class View implements DungeonRooms.View {
        private final WorldGenLevel level;
        private final int chunkX;
        private final int chunkZ;

        public View(WorldGenLevel level, int chunkX, int chunkZ) {
            this.level = level;
            this.chunkX = chunkX;
            this.chunkZ = chunkZ;
        }

        private boolean inside(int x, int z) {
            return (x >> 4) == chunkX && (z >> 4) == chunkZ;
        }

        @Override public boolean isAir(int x, int y, int z) {
            if (!inside(x, z)) return true;
            return level.getBlockState(new BlockPos(x, y, z)).isAir();
        }

        @Override public boolean isVoidBlock(int x, int y, int z) {
            if (!inside(x, z)) return false;
            Block nothing = ThaumcraftOuterLands.eldritchNothing();
            return nothing != null && level.getBlockState(new BlockPos(x, y, z)).is(nothing);
        }

        @Override public boolean isSolidAdjacent(int x, int y, int z) {
            if (!inside(x, z)) return false;
            BlockPos pos = new BlockPos(x, y, z);
            for (Direction direction : Direction.values()) {
                if (!level.getBlockState(pos.relative(direction)).isFaceSturdy(level, pos.relative(direction), direction.getOpposite())) continue;
                return true;
            }
            return false;
        }

        @Override public boolean isCosmeticSolidOrStair(int x, int y, int z) {
            if (!inside(x, z)) return false;
            BlockState state = level.getBlockState(new BlockPos(x, y, z));
            Block stairs = ThaumcraftOuterLands.stairsEldritch();
            if (stairs != null && state.is(stairs)) return true;
            return ThaumcraftOuterLands.isCosmeticSolid(state);
        }
    }

    /** The surface height helper of the eldritch ring. */
    public static int surfaceHeight(WorldGenLevel level, int x, int z) {
        return level.getHeight(Heightmap.Types.WORLD_SURFACE, x, z);
    }
}
