/**
 * Generates the add-on API reference (docs/api/reference) from the sources and the Javadoc of
 * common/src/main/java/thaumcraft/api, so the reference cannot drift from the code.
 *
 * <pre>
 * java scripts/porting/ApiReference.java --write   # regenerate
 * java scripts/porting/ApiReference.java --check   # exit 1 when a generated file is stale
 * </pre>
 *
 * The sources are only parsed, never compiled: no Minecraft classpath is needed.
 */
public final class ApiReference {
    private static final String SOURCE = "common/src/main/java";
    private static final String API = "thaumcraft/api";
    private static final String OUTPUT = "docs/api/reference";
    private static final String HEADER = "<!-- Generated by scripts/porting/ApiReference.java from the Javadoc of thaumcraft.api. "
            + "Do not edit by hand: change the Javadoc and run `java scripts/porting/ApiReference.java --write`. -->\n\n";

    record Member(String kind, String signature, String doc, boolean deprecated, String anchor) {}
    record Type(String pkg, String name, String kind, String declaration, String doc, boolean deprecated,
                List<Member> members, List<Type> nested) {}

    public static void main(String[] args) throws IOException {
        boolean check = List.of(args).contains("--check");
        boolean write = List.of(args).contains("--write");
        if (check == write) {
            System.err.println("usage: java scripts/porting/ApiReference.java --write | --check");
            System.exit(2);
        }
        Path root = Path.of("").toAbsolutePath();
        Map<String, String> files = generate(root);
        Path out = root.resolve(OUTPUT);
        List<String> stale = new ArrayList<>();
        Set<String> existing;
        try (Stream<Path> listed = Files.exists(out) ? Files.list(out) : Stream.empty()) {
            existing = listed.map(path -> path.getFileName().toString()).filter(name -> name.endsWith(".md")).collect(Collectors.toSet());
        }
        for (var entry : files.entrySet()) {
            Path target = out.resolve(entry.getKey());
            String current = Files.exists(target) ? Files.readString(target, StandardCharsets.UTF_8) : null;
            if (entry.getValue().equals(current)) continue;
            stale.add(entry.getKey());
            if (write) {
                Files.createDirectories(out);
                Files.writeString(target, entry.getValue(), StandardCharsets.UTF_8);
            }
        }
        for (String name : existing) {
            if (files.containsKey(name)) continue;
            stale.add(name + " (no longer generated)");
            if (write) Files.delete(out.resolve(name));
        }
        if (check && !stale.isEmpty()) {
            System.err.println("Stale API reference, run java scripts/porting/ApiReference.java --write: " + stale);
            System.exit(1);
        }
        System.out.println((write ? "written: " : "up to date: ") + files.size() + " files"
                + (write && !stale.isEmpty() ? ", changed " + stale : ""));
    }

    static Map<String, String> generate(Path root) throws IOException {
        List<Path> sources;
        try (Stream<Path> walk = Files.walk(root.resolve(SOURCE).resolve(API))) {
            sources = walk.filter(path -> path.toString().endsWith(".java")).sorted().toList();
        }
        JavaCompiler compiler = ToolProvider.getSystemJavaCompiler();
        StandardJavaFileManager manager = compiler.getStandardFileManager(null, Locale.ROOT, StandardCharsets.UTF_8);
        Iterable<? extends JavaFileObject> units = manager.getJavaFileObjectsFromPaths(sources);
        JavacTask task = (JavacTask) compiler.getTask(null, manager, diagnostic -> {}, List.of("-proc:none"), null, units);
        DocTrees trees = DocTrees.instance(task);
        Map<String, List<Type>> packages = new TreeMap<>();
        Map<String, String> packageDocs = new TreeMap<>();
        for (CompilationUnitTree unit : task.parse()) {
            String pkg = unit.getPackageName() == null ? "" : unit.getPackageName().toString();
            packages.computeIfAbsent(pkg, ignored -> new ArrayList<>());
            if (unit.getSourceFile().getName().endsWith("package-info.java")) {
                String doc = trees.getDocComment(new TreePath(new TreePath(unit), unit.getPackage()));
                if (doc != null) packageDocs.put(pkg, markdown(doc, false));
                continue;
            }
            for (Tree declaration : unit.getTypeDecls()) {
                if (declaration instanceof ClassTree type && isPublic(type.getModifiers(), false)) {
                    packages.get(pkg).add(type(trees, new TreePath(new TreePath(unit), type), pkg, type, false));
                }
            }
        }
        Map<String, String> files = new TreeMap<>();
        StringBuilder index = new StringBuilder(HEADER);
        index.append("# `thaumcraft.api` reference\n\n")
                .append("Every public type and member of the add-on API, generated from its Javadoc. The guides are in ")
                .append("[../README.md](../README.md); start with [getting started](../guide/getting-started.md).\n\n");
        for (var entry : packages.entrySet()) {
            List<Type> types = entry.getValue();
            if (types.isEmpty()) continue;
            types.sort((a, b) -> a.name().compareTo(b.name()));
            String file = entry.getKey() + ".md";
            index.append("## [").append(entry.getKey()).append("](").append(file).append(")\n\n");
            String packageDoc = packageDocs.get(entry.getKey());
            if (packageDoc != null) index.append(firstSentence(packageDoc)).append("\n\n");
            index.append("| Type | Summary |\n|---|---|\n");
            for (Type type : types) {
                index.append("| [`").append(type.name()).append("`](").append(file).append('#').append(anchor(type.name())).append(") | ")
                        .append(cell((type.deprecated() ? "**Deprecated.** " : "") + firstSentence(type.doc()))).append(" |\n");
            }
            index.append('\n');
            files.put(file, packagePage(entry.getKey(), packageDoc, types));
        }
        files.put("README.md", index.toString());
        return files;
    }

    private static String packagePage(String pkg, String packageDoc, List<Type> types) {
        StringBuilder page = new StringBuilder(HEADER);
        page.append("# Package `").append(pkg).append("`\n\n[All packages](README.md)\n\n");
        if (packageDoc != null) page.append(packageDoc).append("\n\n");
        page.append("Types: ").append(types.stream().map(type -> "[`" + type.name() + "`](#" + anchor(type.name()) + ")")
                .collect(Collectors.joining(", "))).append("\n\n");
        for (Type type : types) appendType(page, type, "##");
        return page.toString().replaceAll("\n{3,}", "\n\n").stripTrailing() + "\n";
    }

    private static void appendType(StringBuilder page, Type type, String level) {
        page.append(level).append(' ').append(type.name()).append("\n\n");
        page.append("```java\n").append(type.declaration()).append("\n```\n\n");
        if (type.deprecated()) page.append("> **Deprecated.**\n\n");
        if (!type.doc().isBlank()) page.append(type.doc()).append("\n\n");
        // Consecutive members without a comment share one code block; a documented member gets its own.
        List<Member> plain = new ArrayList<>();
        for (Member member : type.members()) {
            if (member.doc().isBlank() && !member.deprecated()) { plain.add(member); continue; }
            flush(page, plain);
            page.append("<a id=\"").append(member.anchor()).append("\"></a>\n");
            page.append("```java\n").append(member.signature()).append("\n```\n\n");
            if (member.deprecated()) page.append("> **Deprecated.**\n\n");
            if (!member.doc().isBlank()) page.append(member.doc()).append("\n\n");
        }
        flush(page, plain);
        for (Type nested : type.nested()) appendType(page, nested, level.length() >= 4 ? level : level + "#");
    }

    private static void flush(StringBuilder page, List<Member> plain) {
        if (plain.isEmpty()) return;
        page.append("```java\n");
        for (Member member : plain) page.append(member.signature()).append('\n');
        page.append("```\n\n");
        plain.clear();
    }

    private static Type type(DocTrees trees, TreePath path, String pkg, ClassTree tree, boolean inInterface) {
        String kind = switch (tree.getKind()) {
            case INTERFACE -> "interface";
            case ENUM -> "enum";
            case RECORD -> "record";
            case ANNOTATION_TYPE -> "@interface";
            default -> "class";
        };
        boolean typeIsInterface = kind.equals("interface") || kind.equals("@interface");
        StringBuilder declaration = new StringBuilder(modifiers(tree.getModifiers(), inInterface, true));
        declaration.append(kind).append(' ').append(tree.getSimpleName()).append(typeParameters(tree.getTypeParameters()));
        if (kind.equals("record")) {
            declaration.append('(').append(tree.getMembers().stream().filter(member -> member instanceof VariableTree variable
                            && !variable.getModifiers().getFlags().contains(Modifier.STATIC))
                    .map(member -> ((VariableTree) member).getType() + " " + ((VariableTree) member).getName())
                    .collect(Collectors.joining(", "))).append(')');
        }
        if (tree.getExtendsClause() != null) declaration.append(" extends ").append(tree.getExtendsClause());
        if (!tree.getImplementsClause().isEmpty()) {
            declaration.append(typeIsInterface ? " extends " : " implements ")
                    .append(tree.getImplementsClause().stream().map(Object::toString).collect(Collectors.joining(", ")));
        }
        List<Member> members = new ArrayList<>();
        List<Type> nested = new ArrayList<>();
        java.util.Map<String, Integer> overloads = new java.util.HashMap<>();
        for (Tree member : tree.getMembers()) {
            TreePath memberPath = new TreePath(path, member);
            if (member instanceof ClassTree inner) {
                if (isPublic(inner.getModifiers(), typeIsInterface)) {
                    nested.add(type(trees, memberPath, pkg, inner, typeIsInterface));
                }
                continue;
            }
            if (member instanceof MethodTree method) {
                if (!isVisible(method.getModifiers(), typeIsInterface)) continue;
                if (kind.equals("record") && method.getName().contentEquals("<init>") && method.getParameters().isEmpty()) continue;
                String name = method.getName().contentEquals("<init>") ? tree.getSimpleName().toString() : method.getName().toString();
                String signature = modifiers(method.getModifiers(), typeIsInterface, false) + typeParameters(method.getTypeParameters())
                        + (method.getReturnType() == null ? "" : method.getReturnType() + " ") + name + "("
                        + method.getParameters().stream().map(ApiReference::parameter).collect(Collectors.joining(", ")) + ")"
                        + (method.getThrows().isEmpty() ? "" : " throws " + method.getThrows().stream().map(Object::toString).collect(Collectors.joining(", ")));
                String anchorName = tree.getSimpleName() + "-" + name;
                int count = overloads.merge(anchorName, 1, Integer::sum);
                members.add(new Member("method", signature, doc(trees, memberPath), deprecated(method.getModifiers()),
                        anchor(count == 1 ? anchorName : anchorName + "-" + count)));
                continue;
            }
            if (member instanceof VariableTree field) {
                boolean constant = tree.getKind() == Tree.Kind.ENUM && field.getType() == null
                        || field.getModifiers().getFlags().isEmpty() && kind.equals("enum") && field.getInitializer() != null
                        && field.getInitializer().getKind() == Tree.Kind.NEW_CLASS && field.getType().toString().equals(tree.getSimpleName().toString());
                if (kind.equals("record") && !field.getModifiers().getFlags().contains(Modifier.STATIC)) continue;
                if (!constant && !isVisible(field.getModifiers(), typeIsInterface)) continue;
                String signature = constant ? field.getName().toString()
                        : modifiers(field.getModifiers(), typeIsInterface, false) + field.getType() + " " + field.getName();
                members.add(new Member(constant ? "constant" : "field", signature, doc(trees, memberPath),
                        deprecated(field.getModifiers()), anchor(tree.getSimpleName() + "-" + field.getName())));
            }
        }
        return new Type(pkg, tree.getSimpleName().toString(), kind, declaration.toString(), doc(trees, path),
                deprecated(tree.getModifiers()), members, nested);
    }

    /** The parameter as written, a varargs one with its {@code ...}; a {@code final} modifier says nothing to a caller. */
    private static String parameter(VariableTree parameter) {
        return parameter.toString().replaceFirst("^final ", "");
    }

    private static boolean isPublic(ModifiersTree modifiers, boolean inInterface) {
        return inInterface || modifiers.getFlags().contains(Modifier.PUBLIC);
    }

    /** Public members, protected ones (a subclass of an add-on sees them), and every member of an interface. */
    private static boolean isVisible(ModifiersTree modifiers, boolean inInterface) {
        Set<Modifier> flags = modifiers.getFlags();
        if (flags.contains(Modifier.PRIVATE)) return false;
        return inInterface || flags.contains(Modifier.PUBLIC) || flags.contains(Modifier.PROTECTED);
    }

    private static boolean deprecated(ModifiersTree modifiers) {
        for (AnnotationTree annotation : modifiers.getAnnotations()) {
            String name = annotation.getAnnotationType().toString();
            if (name.equals("Deprecated") || name.equals("java.lang.Deprecated")) return true;
        }
        return false;
    }

    private static String modifiers(ModifiersTree modifiers, boolean inInterface, boolean type) {
        StringBuilder out = new StringBuilder();
        for (Modifier modifier : List.of(Modifier.PUBLIC, Modifier.PROTECTED, Modifier.ABSTRACT, Modifier.DEFAULT,
                Modifier.STATIC, Modifier.FINAL, Modifier.SEALED, Modifier.NON_SEALED)) {
            if (!modifiers.getFlags().contains(modifier)) continue;
            if (inInterface && (modifier == Modifier.PUBLIC || modifier == Modifier.ABSTRACT && !type)) continue;
            out.append(modifier.toString()).append(' ');
        }
        if (inInterface && out.isEmpty() && !type) return "";
        return out.toString();
    }

    private static String typeParameters(List<? extends TypeParameterTree> parameters) {
        if (parameters.isEmpty()) return "";
        return "<" + parameters.stream().map(Object::toString).collect(Collectors.joining(", ")) + "> ";
    }

    private static String doc(DocTrees trees, TreePath path) {
        String raw = trees.getDocComment(path);
        return raw == null ? "" : markdown(raw, true);
    }

    // ------------------------------------------------------------------ Javadoc to Markdown

    private static final Pattern INLINE = Pattern.compile("\\{@(code|literal|link|linkplain|value)\\s*");

    static String markdown(String javadoc, boolean blockTags) {
        String text = javadoc.replace("\r", "");
        // Split the main description from the block tags.
        List<String> tags = new ArrayList<>();
        Matcher tag = Pattern.compile("(?m)^\\s*@(param|return|returns|throws|exception|deprecated|see|since|apiNote|implNote)\\b").matcher(text);
        String body = text;
        if (tag.find()) {
            body = text.substring(0, tag.start());
            String rest = text.substring(tag.start());
            for (String part : rest.split("(?m)(?=^\\s*@(?:param|return|returns|throws|exception|deprecated|see|since|apiNote|implNote)\\b)")) {
                if (!part.isBlank()) tags.add(part.strip());
            }
        }
        StringBuilder out = new StringBuilder(html(inline(body)).strip());
        if (blockTags && !tags.isEmpty()) {
            List<String> params = new ArrayList<>();
            for (String part : tags) {
                String flat = html(inline(part)).replaceAll("\\s+", " ").strip();
                if (flat.startsWith("@param ")) {
                    String[] pieces = flat.substring(7).split(" ", 2);
                    params.add("- `" + pieces[0] + "`" + (pieces.length > 1 ? " — " + pieces[1] : ""));
                } else if (flat.startsWith("@return")) {
                    out.append("\n\n**Returns:** ").append(flat.replaceFirst("@returns?\\s*", ""));
                } else if (flat.startsWith("@throws ") || flat.startsWith("@exception ")) {
                    String[] pieces = flat.replaceFirst("@(throws|exception) ", "").split(" ", 2);
                    out.append("\n\n**Throws:** `").append(pieces[0]).append('`').append(pieces.length > 1 ? " — " + pieces[1] : "");
                } else if (flat.startsWith("@deprecated")) {
                    out.append("\n\n**Deprecated:** ").append(flat.replaceFirst("@deprecated\\s*", ""));
                } else if (flat.startsWith("@see ")) {
                    out.append("\n\n**See:** ").append(flat.substring(5));
                }
            }
            if (!params.isEmpty()) out.append("\n\n**Parameters:**\n").append(String.join("\n", params));
        }
        return out.toString().replaceAll("[ \\t]+\n", "\n").replaceAll("\n{3,}", "\n\n").strip();
    }

    /** {@code x} and {@link x} as code spans; the content is kept verbatim. */
    private static String inline(String text) {
        StringBuilder out = new StringBuilder();
        int from = 0;
        Matcher matcher = INLINE.matcher(text);
        while (matcher.find(from)) {
            out.append(text, from, matcher.start());
            int depth = 1, end = matcher.end();
            while (end < text.length() && depth > 0) {
                char c = text.charAt(end);
                if (c == '{') depth++;
                else if (c == '}') depth--;
                end++;
            }
            String content = text.substring(matcher.end(), Math.max(matcher.end(), end - 1)).replaceAll("\\s+", " ").strip();
            String kind = matcher.group(1);
            if (kind.equals("link") || kind.equals("linkplain")) {
                String[] pieces = content.split(" ", 2);
                String target = pieces[0].startsWith("#") ? pieces[0].substring(1) : pieces[0].replace('#', '.');
                content = pieces.length > 1 ? pieces[1] : target;
                if (kind.equals("linkplain")) { out.append(content); from = end; continue; }
            }
            out.append(kind.equals("literal") ? content : code(content));
            from = end;
        }
        out.append(text.substring(from));
        return out.toString();
    }

    private static String code(String content) {
        String fence = content.contains("`") ? "``" : "`";
        return fence + (fence.length() > 1 ? " " + content + " " : content) + fence;
    }

    /** The few HTML tags the Javadoc of the API uses. Text outside code spans keeps its entities. */
    private static String html(String text) {
        return text
                .replaceAll("(?i)<pre>\\s*", "\n\n```java\n").replaceAll("(?i)\\s*</pre>", "\n```\n\n")
                .replaceAll("(?i)</?p>", "\n\n")
                .replaceAll("(?i)<br\\s*/?>", "\n")
                .replaceAll("(?i)\\s*<(ul|ol)>\\s*", "\n\n").replaceAll("(?i)\\s*</(ul|ol)>\\s*", "\n\n")
                .replaceAll("(?i)\\s*<li>\\s*", "\n- ").replaceAll("(?i)\\s*</li>", "")
                .replaceAll("(?i)</?(b|strong)>", "**").replaceAll("(?i)</?(em|i)>", "*")
                .replaceAll("(?i)</?(tt|code)>", "`")
                .replaceAll("(?i)<a [^>]*>|</a>", "")
                .replaceAll("(?m)^[ \\t]+(?=- )", "")
                .replaceAll("(?<!\n)\n(?![\n-]|```)", " ")
                .replaceAll(" {2,}", " ");
    }

    private static String firstSentence(String doc) {
        String flat = doc.replaceAll("\\s+", " ").strip();
        int paragraph = doc.indexOf("\n\n");
        if (paragraph > 0) flat = doc.substring(0, paragraph).replaceAll("\\s+", " ").strip();
        Matcher end = Pattern.compile("\\.(\\s|$)").matcher(flat);
        int inCode = 0;
        for (int index = 0; index < flat.length(); index++) {
            char c = flat.charAt(index);
            if (c == '`') inCode ^= 1;
            if (c == '.' && inCode == 0 && (index + 1 == flat.length() || flat.charAt(index + 1) == ' ')) return flat.substring(0, index + 1);
        }
        return flat;
    }

    private static String cell(String text) { return text.replace("|", "\\|"); }

    /** GitHub's heading anchor: lower case, spaces to dashes, punctuation dropped. */
    private static String anchor(String text) {
        return text.toLowerCase(Locale.ROOT).replaceAll("[^a-z0-9 _-]", "").replace(' ', '-');
    }
}
